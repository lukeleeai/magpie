#include <iostream>

#include <string>

#include "stdc++.h"

#define ll long long

using namespace std;



inline int read()

{

    ll s = 0, f = 1;

    char ch = getchar();

    for(; ch < '0' || ch > '9'; ch = getchar()) if(ch == '-') f = - 1;

    for(; ch >= '0' && ch <= '9'; ch = getchar()) s = ((s << 3ll) + (s << 1ll) + (ch ^ 48ll));

    return s * f ;

}

const ll maxn = 1000005;

struct Edge

{

    ll from;

    ll to;

    ll val;

    ll next;

} edge[maxn];



ll head[maxn];

bool vis[maxn];

ll dis[maxn];

ll cnt,n,m,b;



void add(ll u,ll v,ll w)

{

    edge[cnt].from = u;

    edge[cnt].to=v;

    edge[cnt].val = w;

    edge[cnt].next = head[u];

    head[u] = cnt++;

}



void spfa(ll s)

{

    queue<ll>q ;

    for(ll i = 1 ; i <= n ; i ++) dis[i] = 999999999 ;

    memset(vis, false, sizeof(vis)) ;

    q.push(s) ;

    dis[s] = 0 ;

    while(!q.empty())

    {

        ll u = q.front();

        q.pop();

        vis[u] = false;

        for(ll i = head[u] ; i != -1 ; i = edge[i].next )

        {

            ll v = edge[i].to ;

            if(dis[v] > dis[u] + edge[i].val)

            {

                dis[v] = dis[u] + edge[i].val ;

                if(!vis[v])

                {

                    vis[v] = true ;

                    q.push(v) ;

                }

            }

        }

    }

}



