#include "stdc++.h"

using namespace std;



int main(){

  int i1=-1,j1=-1;

  string s;

  cin >> s;

  bool unbalanced=false;

  for (int i = 1; i < s.length(); ++i)

  {

    if (unbalanced)

    {

      break;

    }

    if (s[i]==s[i-1])

    {

      i1=i-1;

      j1=i;

      unbalanced=true;

    }

    if (i>1){

      if (s[i]==s[i-2]){

        i1=i-2;

        j1=i;

        unbalanced=true;

      }

    }

  }

  if (i1==-1) cout << -1 << " " << -1;

  else cout << i1+1 << " " << j1+1;

  return 0;

}