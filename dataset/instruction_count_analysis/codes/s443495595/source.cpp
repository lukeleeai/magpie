#include <stdio.h>



void init(int* h, int* w, int c[][10], int a[][210]) {

  int i, j;

  scanf("%d%d", h, w);

  for (i = 0; i < 10; i++) {

    for (j = 0; j < 10; j++) {

      scanf("%d", &c[i][j]);

    }

  }

  for (i = 0; i < *h; i++) {

    for (j = 0; j < *w; j++) {

      scanf("%d", &a[i][j]);

    }

  }

  return;

}



void warshall_floyd(int c[][10]) {

  int k, i, j;

  for (k = 0; k < 10; k++) {

    for (i = 0; i < 10; i++) {

      for (j = 0; j < 10; j++) {

	if (c[i][j] > c[i][k] + c[k][j]) {

	  c[i][j] = c[i][k] + c[k][j];

	}

      }

    }

  }

  return;

}



void ans(int h, int w, int c[][10], int a[][210]) {

  int i, j;

  int ans = 0;

  for (i = 0; i < h; i++) {

    for (j = 0; j < w; j++) {

      if (a[i][j] != -1) {

	ans += c[a[i][j]][1];

      }

    }

  }

  printf("%d\n", ans);

  return;

}



void solve() {

   int h, w, i, j;

   int c[10][10];

   int a[210][210];

   init(&h, &w, c, a);

   warshall_floyd(c);

   ans(h, w, c, a);

   return;

}



int main() {

  solve();

}



