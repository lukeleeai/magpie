vector<vector<int>> G1(100000),G2(100000);

vector<bool> visit1(100000, false), visit2(100000, false);

int timer = 0;



//?????????????????????DFS?????????????????????????????????????????????????????????

void dfs1(int u,vector<int>& prenum) {

	visit1[u] = true;

	for (int v : G1[u]) {

		if (visit1[v] == false) {

			dfs1(v, prenum);

		}

	}

	prenum[timer++] = u;

}



